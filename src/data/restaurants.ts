export const createDefaultTables = (count: number, prefix: string = 'T'): Table[] => {
  return Array.from({ length: count }, (_, i) => ({
    id: `tbl-${prefix.toLowerCase()}-${i + 1}`,
    number: i + 1,
    seats: (i % 3 === 0) ? 6 : (i % 2 === 0) ? 4 : 2,
    status: (i === 1) ? 'occupied' : (i === 4) ? 'reserved' : 'available',
    qrToken: `QR-${prefix.toUpperCase()}-${i + 1}-REST-TOKEN`,
  }));
};

